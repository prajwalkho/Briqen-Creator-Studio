import crypto from 'crypto';
import type {
  ExtractedSceneDTO,
  LLMExtractScenesRequest,
  LLMExtractScenesResponse,
  LLMGenerateScriptRequest,
  LLMImproveScriptRequest,
  LLMProvider,
  LLMProviderCapabilities,
  LLMScriptResponse,
} from '../../interfaces/llmProvider.ts';
import { extractedScenesArraySchema } from '../../schemas.ts';

export class MockLLMProvider implements LLMProvider {
  readonly name = 'mock';
  readonly capabilities: LLMProviderCapabilities = {
    name: 'mock',
    isMock: true,
    supportsSearchGrounding: false,
    supportsStructuredJson: true,
    limitations: [
      'Deterministic offline simulator for development and automated tests — output is not generated by a live LLM.',
    ],
  };

  async generateScript(request: LLMGenerateScriptRequest): Promise<LLMScriptResponse> {
    const dur = Math.max(10, request.targetDurationSec || 30);
    const introEnd = Math.max(4, Math.round(dur * 0.2));
    const midEnd = Math.max(introEnd + 5, Math.round(dur * 0.72));
    const subject = request.brandName || request.topic || request.title;

    const introduction = [
      `[00:00 - 00:${String(introEnd).padStart(2, '0')}] INTRODUCTION & HOOK (${request.contentType})`,
      `Visual: Tight studio frame introducing ${subject} tailored for ${request.targetAudience || 'creators'}.`,
      `Voiceover: Ready to rethink ${request.topic || request.title}? Meet ${subject} — built for ${request.platform}.`,
    ].join('\n');

    const mainContent = [
      `[00:${String(introEnd).padStart(2, '0')} - 00:${String(midEnd).padStart(2, '0')}] MAIN CONTENT`,
      `Visual: Dynamic product walkthrough showcasing real-world ${request.contentType.replace('_', ' ')} workflow.`,
      `Voiceover: Every moment matters when delivering ${request.marketingObjective}. With a ${request.toneOfVoice.toLowerCase()} pace in ${request.language}, ${subject} removes friction from concept to finish.`,
    ].join('\n');

    const conclusion = [
      `[00:${String(midEnd).padStart(2, '0')} - 00:${String(dur).padStart(2, '0')}] CONCLUSION & CTA`,
      `Visual: Clean closing lockup with ${subject} wordmark and call-to-action prompt.`,
      `Voiceover: Start your next ${request.contentType.replace('_', ' ')} project with ${subject} today.`,
    ].join('\n');

    const fullScript = [introduction, '', mainContent, '', conclusion].join('\n');

    return {
      content: fullScript,
      sections: { introduction, mainContent, conclusion },
      aiModelUsed: 'mock-script-provider',
      aiNotes: 'Mock Mode: Deterministic script generated locally for testing without external LLM calls.',
      groundingSources: [],
      usage: {
        promptTokens: 120,
        completionTokens: 185,
        totalTokens: 305,
        estimatedCostUsd: 0,
        provider: 'mock',
        isMock: true,
        providerRequestId: `mock-llm-${crypto.randomUUID().slice(0, 8)}`,
      },
    };
  }

  async improveScript(request: LLMImproveScriptRequest): Promise<LLMScriptResponse> {
    const labelMap: Record<LLMImproveScriptRequest['action'], string> = {
      rewrite: 'REWRITE',
      grammar: 'GRAMMAR',
      clarity: 'CLARITY',
      engaging: 'ENGAGING',
      tone: 'TONE',
      expand: 'EXPAND',
      shorten: 'SHORTEN',
      alternative: 'ALTERNATIVE',
    };

    const revised = `${request.currentContent.trim()}\n\n[MOCK REVISION: ${labelMap[request.action]}] Refined for ${request.platform} in ${request.language}${request.targetTone ? ` (${request.targetTone})` : ''}.`;

    return {
      content: revised,
      aiModelUsed: 'mock-script-provider',
      aiNotes: `Mock Mode: Improvement (${request.action}) applied locally without external LLM calls.`,
      groundingSources: [],
      usage: {
        promptTokens: 95,
        completionTokens: 140,
        totalTokens: 235,
        estimatedCostUsd: 0,
        provider: 'mock',
        isMock: true,
        providerRequestId: `mock-llm-${crypto.randomUUID().slice(0, 8)}`,
      },
    };
  }

  async extractScenes(request: LLMExtractScenesRequest): Promise<LLMExtractScenesResponse> {
    const paragraphs = request.scriptContent
      .split(/\n\s*\n/)
      .map((p) => p.trim())
      .filter(Boolean);

    const chunks = paragraphs.length >= 2 ? paragraphs.slice(0, 6) : [request.scriptContent.trim()];
    const rawScenes: ExtractedSceneDTO[] = chunks.map((block, idx) => ({
      sceneNumber: idx + 1,
      title: `Scene ${idx + 1}: ${
        idx === 0 ? 'Opening Hook' : idx === chunks.length - 1 ? 'Closing CTA' : `Story Beat ${idx}`
      }`,
      narration: block.replace(/\[.*?\]/g, '').trim().slice(0, 260),
      visualDescription: `Cinematic ${request.aspectRatio} frame tailored for ${request.platform}, balanced studio lighting.`,
      imagePrompt: `High-contrast commercial photography frame, ${request.aspectRatio} composition, dramatic studio lighting: ${block.slice(0, 140)}`,
      videoPrompt: `Smooth slow push-in camera motion, crisp commercial cinematography: ${block.slice(0, 140)}`,
      durationSec: 5,
      transition: idx === 0 ? 'fade' : 'dissolve',
      mediaPreference: idx % 2 === 0 ? 'image' : 'video',
    }));

    const validated = extractedScenesArraySchema.parse(rawScenes).map((s, idx) => ({
      sceneNumber: s.sceneNumber ?? idx + 1,
      title: s.title,
      narration: s.narration,
      visualDescription: s.visualDescription,
      imagePrompt: s.imagePrompt,
      videoPrompt: s.videoPrompt,
      durationSec: s.durationSec,
      transition: s.transition,
      mediaPreference: s.mediaPreference,
    }));

    return {
      scenes: validated,
      modelUsed: 'mock-scene-extractor',
      usage: {
        promptTokens: 110,
        completionTokens: 240,
        totalTokens: 350,
        estimatedCostUsd: 0,
        provider: 'mock',
        isMock: true,
        providerRequestId: `mock-scene-${crypto.randomUUID().slice(0, 8)}`,
      },
    };
  }
}
